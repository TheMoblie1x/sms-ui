    ),
    Question.Rating(
        id = "experience",
        text = "How would you rate your interview experience?",
        maxStars = 5
    )
)


suspend fun uploadFileToServer(file: File): Boolean {
    delay(1000) // simulate network delay
    println("Uploaded: ${file.name}")
    return true
}

