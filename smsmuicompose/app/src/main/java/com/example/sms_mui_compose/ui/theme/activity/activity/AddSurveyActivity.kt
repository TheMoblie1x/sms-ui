sealed class Question(
    val id: String,
    val text: String,
    val type: QuestionType
) {
    class FileUpload(
        id: String,
        text: String,
        val allowedMimeTypes: List<String>,
        val maxFileSizeMB: Int
    ) : Question(id, text, QuestionType.FileUpload)

    class TextInput(
        id: String,
        text: String
    ) : Question(id, text, QuestionType.ShortText)

    class Rating(
        id: String,
        text: String,
        val maxStars: Int = 5
    ) : Question(id, text, QuestionType.ParagraphText)
}

val dummyQuestions = listOf(
